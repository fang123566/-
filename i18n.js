  function updateButtonState() {
    var zhBtn = document.getElementById('i18nBtnZh');
    var enBtn = document.getElementById('i18nBtnEn');
    if (!zhBtn || !enBtn) return;
    if (currentLang === 'zh') {
      zhBtn.classList.add('active');
      enBtn.classList.remove('active');
    } else {
      enBtn.classList.add('active');
      zhBtn.classList.remove('active');
    }
  }

  /* ─── 确保 hero-nav 不遮挡按钮 ─── */
  function adjustPosition() {
    var heroNav = document.querySelector('.hero-nav');
    var toggle = document.getElementById('i18nToggle');
    if (!toggle) return;
    if (heroNav) {
      var rect = heroNav.getBoundingClientRect();
      toggle.style.top = (rect.bottom + 8) + 'px';
    }
  }

  /* ─── 初始化 ─── */
  function init() {
    createToggleButton();
    adjustPosition();
    if (currentLang === 'en') {
      applyTranslations();
    }
    // 监听 DOM 变化，以处理动态加载的内容
    var observer = new MutationObserver(function () {
      if (currentLang === 'en' && !isApplyingTranslations) {
        applyTranslations();
      }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
