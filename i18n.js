  /* 规范空白：连续空白→单空格，首尾去白 */
  function norm(s) { return s.replace(/[\u201c\u201d]/g, '"').replace(/[\u2018\u2019]/g, "'").replace(/\s+/g, ' ').replace(/ ?([，。；：！？、]) ?/g, '$1').trim(); }

  function walkTextNodes(root) {
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
    var nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    return nodes;
  }

  var BLOCK_SEL = 'h1,h2,h3,h4,h5,h6,p,th,td,li,dt,dd,button,figcaption,label,summary,caption,div,span';

  function applyTranslations() {
    if (isApplyingTranslations) return;
    isApplyingTranslations = true;
    try {
    /* ① 元素级翻译 — 块级元素整体匹配 */
    document.querySelectorAll(BLOCK_SEL).forEach(function (el) {
      if (el.closest('.i18n-toggle')) return;
      if (el.querySelectorAll('div,p,ul,ol,table,h1,h2,h3,h4,h5,h6').length) return;
      var n = norm(el.textContent);
      if (n.length < 2) return;
      if (merged[n]) {
        if (!originalTexts.has(el)) originalTexts.set(el, el.innerHTML);
        el.textContent = merged[n];
      }
    });

    /* ② 文本节点遍历 — 处理 span / a / div 等内联文本 */
    walkTextNodes(document.body).forEach(function (node) {
      if (originalTexts.has(node.parentElement)) return;
      if (node.parentElement && node.parentElement.closest('.i18n-toggle')) return;
      var raw = node.textContent;
      var n = norm(raw);
      if (!n || n.length < 1) return;
      if (merged[n]) {
        if (!originalTexts.has(node)) originalTexts.set(node, raw);
        node.textContent = merged[n];
      }
    });

    /* ③ 文档标题 */
    var nt = norm(document.title);
    if (merged[nt]) { savedTitle = document.title; document.title = merged[nt]; }

    /* ④ alt / title / placeholder / aria-label 属性 */
    document.querySelectorAll('[alt],[aria-label],[placeholder],[title]').forEach(function (el) {
      ['alt', 'aria-label', 'placeholder', 'title'].forEach(function (attr) {
        var val = el.getAttribute(attr);
        if (!val) return;
        var nv = norm(val);
        if (merged[nv]) {
          var key = attr + '::' + nv;
          if (!originalAttrs.has(key)) originalAttrs.set(key, { el: el, attr: attr, original: val });
          el.setAttribute(attr, merged[nv]);
        }
      });
    });
    } finally {
      isApplyingTranslations = false;
    }
  }

